//! Overlay contract: where host UI (menus, text) sits over the visuals, and how the present
//! pass treats those places.
//!
//! A host declares up to [`MAX_OVERLAY_REGIONS`] [`OverlayRegion`]s, each a rounded rectangle
//! in normalized viewport coordinates (origin top-left) with [`MODE_LIGHT_TEXT`] (a luminance
//! ceiling for light text), [`MODE_DARK_TEXT`] (a floor for dark text), [`MODE_DESATURATE`],
//! [`MODE_BLUR`], [`MODE_DAMP_MOTION`] and [`MODE_DAMP_FLASH`] bits. An [`OverlayConfig`] adds
//! the viewport, the contrast ratio, the host's presentation intensity and the reduced-motion
//! preference. [`pack`] turns both into the std140 `OverlayUniforms` block
//! (`conformance/packing/overlay-uniforms.schema.json`) that `shaders/present/present.glsl`
//! reads; every policy number the shader applies is computed here, so hosts and shaders do no
//! contrast arithmetic. Regions and the config are data: which UI is shown, and where, stays
//! with the host.
//!
//! The contrast bound is the WCAG relative-luminance one. Light text (luminance 1) on a
//! background of luminance `L` has contrast `1.05 / (L + 0.05)`, so a ratio `r` needs
//! `L <= 1.05 / r - 0.05`; dark text (luminance 0) needs `L >= 0.05 * r - 0.05`. The packed
//! bounds are tightened by [`CONTRAST_MARGIN`] so GPU rounding in the encode cannot cross them.
//!
//! The vectors are `conformance/packing/overlay-uniforms.json`, generated by the
//! standard-library model `tools/overlay-uniforms-vectors.py`.

use crate::limiter::FlashConfig;

/// Most regions one overlay declares.
pub const MAX_OVERLAY_REGIONS: usize = 8;

/// Size in bytes of the packed std140 `OverlayUniforms` block.
pub const OVERLAY_UNIFORMS_SIZE: usize = 320;

/// The region's background is held at or below the light-text luminance ceiling.
pub const MODE_LIGHT_TEXT: u32 = 1;
/// The region's background is held at or above the dark-text luminance floor.
pub const MODE_DARK_TEXT: u32 = 2;
/// The region is desaturated by its strength.
pub const MODE_DESATURATE: u32 = 4;
/// The region is blurred by its strength.
pub const MODE_BLUR: u32 = 8;
/// Frame-to-frame motion inside the region is damped by its strength.
pub const MODE_DAMP_MOTION: u32 = 16;
/// Per-frame luminance steps inside the region are limited by its strength, and the region is
/// a stricter area for the flash analyzer
/// ([`FlashAnalyzer::set_overlay`](crate::limiter::FlashAnalyzer::set_overlay)).
pub const MODE_DAMP_FLASH: u32 = 32;
/// Every defined mode bit.
pub const MODE_MASK: u32 = 63;

/// WCAG AA contrast for body text, the default [`OverlayConfig::contrast_ratio`].
pub const DEFAULT_CONTRAST_RATIO: f64 = 4.5;

/// Relative luminance by which the packed ceiling is lowered and the floor raised, so the
/// shader's float error cannot cross the exact WCAG bound.
pub const CONTRAST_MARGIN: f64 = 1.0e-4;

/// The per-frame interval the damping constants are stated for, in milliseconds (60 Hz).
pub const REFERENCE_FRAME_MS: f64 = 1000.0 / 60.0;

/// Fraction of the previous presented frame kept inside a [`MODE_DAMP_MOTION`] region at full
/// strength, per 60 Hz frame.
pub const REGION_TEMPORAL_KEEP: f64 = 0.9;
/// Largest relative-luminance step per 60 Hz frame inside a [`MODE_DAMP_FLASH`] region at full
/// strength.
pub const REGION_MAX_LUMINANCE_STEP: f64 = 0.01;
/// Fraction of the previous presented frame kept everywhere under reduced motion, per 60 Hz
/// frame.
pub const REDUCED_MOTION_TEMPORAL_KEEP: f64 = 0.6;
/// Largest relative-luminance step per 60 Hz frame everywhere under reduced motion.
pub const REDUCED_MOTION_MAX_LUMINANCE_STEP: f64 = 0.04;
/// Factor applied to the host's presentation intensity under reduced motion.
pub const REDUCED_MOTION_INTENSITY: f64 = 0.5;
/// Blur radius at full strength, as a fraction of the viewport height.
pub const BLUR_RADIUS: f64 = 0.012;
/// General flashes per second a reduced-motion flash config allows at most.
pub const REDUCED_MOTION_MAX_FLASH_HZ: f64 = 1.0;
/// Field fraction a reduced-motion flash config allows at most.
pub const REDUCED_MOTION_MAX_FIELD_AREA: f64 = 0.1;
/// Red flashes per second a reduced-motion flash config allows at most.
pub const REDUCED_MOTION_MAX_RED_FLASHES: u32 = 1;

/// One overlay region: a rounded rectangle in normalized viewport coordinates, origin
/// top-left, x right and y down. An element of the region array, so it carries no
/// `struct_size`.
#[repr(C)]
#[derive(Clone, Copy, Debug, Default, PartialEq)]
pub struct OverlayRegion {
    /// Left edge, a fraction of the viewport width.
    pub x: f64,
    /// Top edge, a fraction of the viewport height.
    pub y: f64,
    /// Width, a fraction of the viewport width, `>= 0`.
    pub width: f64,
    /// Height, a fraction of the viewport height, `>= 0`.
    pub height: f64,
    /// Corner radius, a fraction of the viewport height, `[0, 1]`; clamped to half the
    /// shorter side.
    pub corner_radius: f64,
    /// Width of the soft edge outside the rectangle, a fraction of the viewport height,
    /// `[0, 1]`. The contrast bound holds in full inside the rectangle.
    pub feather: f64,
    /// Strength of the desaturate, blur and damping treatments, `[0, 1]`. The contrast bound
    /// does not depend on it.
    pub strength: f64,
    /// `MODE_*` bits; light and dark text are exclusive.
    pub mode: u32,
    /// Must be 0.
    pub reserved: u32,
}

/// Viewport and presentation inputs of one overlay.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct OverlayConfig {
    /// Output width in pixels, `> 0`.
    pub viewport_width: f64,
    /// Output height in pixels, `> 0`.
    pub viewport_height: f64,
    /// WCAG contrast ratio the text regions guarantee against white (light text) or black
    /// (dark text) text, `[1, 21]`.
    pub contrast_ratio: f64,
    /// The host's presentation intensity before reduced motion, `[0, 1]`.
    pub intensity: f64,
    /// Interval since the previous presented frame in milliseconds, `(0, 1000]`.
    pub frame_interval_ms: f64,
    /// Output alpha outside contrast regions, `[0, 1]`; text regions are always opaque.
    pub alpha: f64,
    /// Levels per channel of the output, 0 for a float target or `2..=65535`. The encode
    /// rounds text-region pixels toward the bound on this grid.
    pub output_levels: u32,
    /// The user asked for reduced motion.
    pub reduced_motion: bool,
    /// Write premultiplied alpha.
    pub premultiplied_alpha: bool,
}

impl OverlayConfig {
    /// A 1920 by 1080 8-bit output at 60 Hz, WCAG AA, full intensity, opaque, motion allowed.
    pub const DEFAULT: OverlayConfig = OverlayConfig {
        viewport_width: 1920.0,
        viewport_height: 1080.0,
        contrast_ratio: DEFAULT_CONTRAST_RATIO,
        intensity: 1.0,
        frame_interval_ms: REFERENCE_FRAME_MS,
        alpha: 1.0,
        output_levels: 255,
        reduced_motion: false,
        premultiplied_alpha: false,
    };

    /// Refuses a value outside its documented range.
    pub fn validate(&self) -> Result<(), OverlayError> {
        let positive = |v: f64| v.is_finite() && v > 0.0;
        if !positive(self.viewport_width) || !positive(self.viewport_height) {
            return Err(OverlayError::Viewport);
        }
        if !(1.0..=21.0).contains(&self.contrast_ratio) {
            return Err(OverlayError::ContrastRatio);
        }
        if !unit(self.intensity) {
            return Err(OverlayError::Intensity);
        }
        if !(positive(self.frame_interval_ms) && self.frame_interval_ms <= 1000.0) {
            return Err(OverlayError::FrameInterval);
        }
        if !unit(self.alpha) {
            return Err(OverlayError::Alpha);
        }
        if self.output_levels == 1 || self.output_levels > 65535 {
            return Err(OverlayError::OutputLevels);
        }
        Ok(())
    }

    /// Relative luminance the background of a light-text region stays at or below.
    pub fn luminance_ceiling(&self) -> f64 {
        1.05 / self.contrast_ratio - 0.05 - CONTRAST_MARGIN
    }

    /// Relative luminance the background of a dark-text region stays at or above.
    pub fn luminance_floor(&self) -> f64 {
        0.05 * self.contrast_ratio - 0.05 + CONTRAST_MARGIN
    }

    /// The presentation intensity visuals read (`presentation1.x`): the host's, halved under
    /// reduced motion.
    pub fn presentation_intensity(&self) -> f64 {
        if self.reduced_motion {
            self.intensity * REDUCED_MOTION_INTENSITY
        } else {
            self.intensity
        }
    }

    /// `base` tightened for reduced motion: at most [`REDUCED_MOTION_MAX_FLASH_HZ`] general
    /// flashes, [`REDUCED_MOTION_MAX_RED_FLASHES`] red flashes and
    /// [`REDUCED_MOTION_MAX_FIELD_AREA`] of a field. Without reduced motion, `base` unchanged.
    /// Never loosens a value.
    pub fn flash_config(&self, base: FlashConfig) -> FlashConfig {
        if !self.reduced_motion {
            return base;
        }
        FlashConfig {
            max_flash_hz: base.max_flash_hz.min(REDUCED_MOTION_MAX_FLASH_HZ),
            max_field_area: base.max_field_area.min(REDUCED_MOTION_MAX_FIELD_AREA),
            max_red_flashes: base.max_red_flashes.min(REDUCED_MOTION_MAX_RED_FLASHES),
            ..base
        }
    }

    /// The fraction of 60 Hz frames this frame interval spans, at most 1.
    fn frames(&self) -> f64 {
        (self.frame_interval_ms / REFERENCE_FRAME_MS).min(1.0)
    }
}

impl Default for OverlayConfig {
    fn default() -> Self {
        Self::DEFAULT
    }
}

impl OverlayRegion {
    /// Refuses a region outside its documented ranges.
    pub fn validate(&self) -> Result<(), OverlayError> {
        let finite = [self.x, self.y, self.width, self.height]
            .iter()
            .all(|v| v.is_finite());
        if !finite || self.width < 0.0 || self.height < 0.0 {
            return Err(OverlayError::RegionRect);
        }
        if !unit(self.corner_radius) || !unit(self.feather) {
            return Err(OverlayError::RegionShape);
        }
        if !unit(self.strength) {
            return Err(OverlayError::RegionStrength);
        }
        let both = MODE_LIGHT_TEXT | MODE_DARK_TEXT;
        if self.mode & !MODE_MASK != 0 || self.mode & both == both || self.reserved != 0 {
            return Err(OverlayError::RegionMode);
        }
        Ok(())
    }

    /// Whether this region overlaps grid cell `(column, row)` of a `columns` by `rows` grid,
    /// counting its feather as part of it. Every pixel the present pass treats lies in a cell
    /// this reports.
    pub fn covers_cell(&self, column: u32, row: u32, columns: u32, rows: u32) -> bool {
        let (c0, c1) = (
            column as f64 / columns as f64,
            (column + 1) as f64 / columns as f64,
        );
        let (r0, r1) = (row as f64 / rows as f64, (row + 1) as f64 / rows as f64);
        // The feather is in viewport heights; a viewport height is at least as wide as the
        // same fraction of the width for any landscape output, and the grid has no aspect, so
        // the feather widens both axes by its full value.
        let f = self.feather;
        let (x0, x1) = (self.x - f, self.x + self.width + f);
        let (y0, y1) = (self.y - f, self.y + self.height + f);
        self.width > 0.0 && self.height > 0.0 && x0 < c1 && x1 > c0 && y0 < r1 && y1 > r0
    }
}

/// Why an overlay config, region or region list was refused.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum OverlayError {
    /// A viewport size was not a finite positive number.
    Viewport,
    /// The contrast ratio was not in `[1, 21]`.
    ContrastRatio,
    /// The intensity was not in `[0, 1]`.
    Intensity,
    /// The frame interval was not in `(0, 1000]`.
    FrameInterval,
    /// The alpha was not in `[0, 1]`.
    Alpha,
    /// The output levels were 1 or above 65535.
    OutputLevels,
    /// More than [`MAX_OVERLAY_REGIONS`] regions.
    RegionCount,
    /// A region's rectangle was not finite or had a negative size.
    RegionRect,
    /// A region's corner radius or feather was not in `[0, 1]`.
    RegionShape,
    /// A region's strength was not in `[0, 1]`.
    RegionStrength,
    /// A region's mode had an unknown bit, both text bits, or a nonzero reserved field.
    RegionMode,
    /// The output buffer was smaller than [`OVERLAY_UNIFORMS_SIZE`].
    Capacity,
}

impl core::fmt::Display for OverlayError {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        write!(f, "invalid overlay input: {self:?}")
    }
}
impl core::error::Error for OverlayError {}

/// `value` in `[0, 1]`; NaN is refused.
fn unit(value: f64) -> bool {
    (0.0..=1.0).contains(&value)
}

/// Packs `config` and `regions` into the std140 `OverlayUniforms` block at the start of `out`,
/// as little-endian float32, with every unused byte zero. Refuses invalid input before
/// writing. Does not allocate.
///
/// Layout (offsets in bytes; schema `conformance/packing/overlay-uniforms.schema.json`):
///
/// - 0 `overlay0`: region count, luminance ceiling, luminance floor, output levels
/// - 16 `overlay1`: presentation intensity, temporal keep, largest luminance step,
///   premultiplied alpha (0 or 1)
/// - 32 `overlay2`: region temporal keep, region largest luminance step, blur radius (viewport
///   heights), aspect (width / height)
/// - 48 `overlay3`: output alpha, viewport height in pixels, reduced motion (0 or 1), 0
/// - 64 `regionRect[8]`: x, y, width, height
/// - 192 `regionShape[8]`: corner radius, feather, strength, mode bits (as a float)
///
/// The temporal keep and step outside regions are 0 and 1 (no damping) unless reduced motion
/// is set. Keeps and steps scale linearly with the frame interval up to one 60 Hz frame.
pub fn pack(
    config: &OverlayConfig,
    regions: &[OverlayRegion],
    out: &mut [u8],
) -> Result<(), OverlayError> {
    config.validate()?;
    if regions.len() > MAX_OVERLAY_REGIONS {
        return Err(OverlayError::RegionCount);
    }
    for region in regions {
        region.validate()?;
    }
    let Some(out) = out.get_mut(..OVERLAY_UNIFORMS_SIZE) else {
        return Err(OverlayError::Capacity);
    };
    out.fill(0);
    let frames = config.frames();
    let keep = |keep60: f64| 1.0 - (1.0 - keep60) * frames;
    let (global_keep, global_step) = if config.reduced_motion {
        (
            keep(REDUCED_MOTION_TEMPORAL_KEEP),
            REDUCED_MOTION_MAX_LUMINANCE_STEP * frames,
        )
    } else {
        (0.0, 1.0)
    };
    let flag = |b: bool| if b { 1.0 } else { 0.0 };
    let head: [[f64; 4]; 4] = [
        [
            regions.len() as f64,
            config.luminance_ceiling(),
            config.luminance_floor(),
            config.output_levels as f64,
        ],
        [
            config.presentation_intensity(),
            global_keep,
            global_step,
            flag(config.premultiplied_alpha),
        ],
        [
            keep(REGION_TEMPORAL_KEEP),
            REGION_MAX_LUMINANCE_STEP * frames,
            BLUR_RADIUS,
            config.viewport_width / config.viewport_height,
        ],
        [
            config.alpha,
            config.viewport_height,
            flag(config.reduced_motion),
            0.0,
        ],
    ];
    for (i, values) in head.iter().enumerate() {
        put(out, 16 * i, values);
    }
    for (i, r) in regions.iter().enumerate() {
        put(out, 64 + 16 * i, &[r.x, r.y, r.width, r.height]);
        let shape = [r.corner_radius, r.feather, r.strength, r.mode as f64];
        put(out, 192 + 16 * i, &shape);
    }
    Ok(())
}

fn put(out: &mut [u8], offset: usize, values: &[f64; 4]) {
    for (i, v) in values.iter().enumerate() {
        let at = offset + 4 * i;
        out[at..at + 4].copy_from_slice(&(*v as f32).to_le_bytes());
    }
}

/// Marks in `mask` (row-major, `columns * rows` long) every flash-analyzer grid cell a
/// [`MODE_DAMP_FLASH`] region with nonzero strength covers, and clears the rest. Refuses
/// invalid regions, more than [`MAX_OVERLAY_REGIONS`], or a mask of another length.
pub fn flash_mask(
    regions: &[OverlayRegion],
    columns: u32,
    rows: u32,
    mask: &mut [bool],
) -> Result<(), OverlayError> {
    if regions.len() > MAX_OVERLAY_REGIONS {
        return Err(OverlayError::RegionCount);
    }
    for region in regions {
        region.validate()?;
    }
    if columns == 0 || rows == 0 || mask.len() != (columns * rows) as usize {
        return Err(OverlayError::Capacity);
    }
    for row in 0..rows {
        for column in 0..columns {
            mask[(row * columns + column) as usize] = regions.iter().any(|r| {
                r.mode & MODE_DAMP_FLASH != 0
                    && r.strength > 0.0
                    && r.covers_cell(column, row, columns, rows)
            });
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn f32_at(out: &[u8], offset: usize) -> f32 {
        f32::from_le_bytes(out[offset..offset + 4].try_into().unwrap())
    }

    #[test]
    fn default_bounds_meet_wcag_aa() {
        let c = OverlayConfig::DEFAULT;
        assert!(c.luminance_ceiling() < 1.05 / 4.5 - 0.05);
        assert!((1.05 / (c.luminance_ceiling() + 0.05)) > 4.5);
        assert!(c.luminance_floor() > 0.175);
        assert!(((c.luminance_floor() + 0.05) / 0.05) > 4.5);
    }

    #[test]
    fn pack_zeroes_unused_regions_and_refuses_bad_input() {
        let region = OverlayRegion {
            x: 0.1,
            y: 0.8,
            width: 0.8,
            height: 0.15,
            corner_radius: 0.01,
            feather: 0.02,
            strength: 1.0,
            mode: MODE_LIGHT_TEXT | MODE_DAMP_FLASH,
            reserved: 0,
        };
        let mut out = [0xffu8; OVERLAY_UNIFORMS_SIZE];
        pack(&OverlayConfig::DEFAULT, &[region], &mut out).unwrap();
        assert_eq!(f32_at(&out, 0), 1.0);
        assert_eq!(f32_at(&out, 64 + 4), 0.8);
        assert_eq!(f32_at(&out, 192 + 12), 33.0);
        assert!(out[80..192].iter().all(|&b| b == 0));
        let bad = OverlayRegion {
            mode: MODE_LIGHT_TEXT | MODE_DARK_TEXT,
            ..region
        };
        assert_eq!(
            pack(&OverlayConfig::DEFAULT, &[bad], &mut out),
            Err(OverlayError::RegionMode)
        );
        let mut short = [0u8; 16];
        assert_eq!(
            pack(&OverlayConfig::DEFAULT, &[], &mut short),
            Err(OverlayError::Capacity)
        );
    }

    #[test]
    fn reduced_motion_tightens_and_halves_intensity() {
        let rm = OverlayConfig {
            reduced_motion: true,
            ..OverlayConfig::DEFAULT
        };
        assert_eq!(rm.presentation_intensity(), 0.5);
        let tight = rm.flash_config(FlashConfig::DEFAULT);
        assert_eq!(tight.max_flash_hz, 1.0);
        assert_eq!(tight.max_red_flashes, 1);
        assert_eq!(tight.max_field_area, 0.1);
        assert_eq!(tight.validate(), Ok(()));
        let base = OverlayConfig::DEFAULT.flash_config(FlashConfig::DEFAULT);
        assert_eq!(base, FlashConfig::DEFAULT);
    }

    #[test]
    fn mask_covers_the_bottom_bar() {
        let bar = OverlayRegion {
            x: 0.0,
            y: 0.875,
            width: 1.0,
            height: 0.125,
            strength: 1.0,
            mode: MODE_DAMP_FLASH,
            ..OverlayRegion::default()
        };
        let mut mask = [false; 16];
        flash_mask(&[bar], 4, 4, &mut mask).unwrap();
        assert_eq!(mask.iter().filter(|&&m| m).count(), 4);
        assert!(mask[12..].iter().all(|&m| m));
    }
}
