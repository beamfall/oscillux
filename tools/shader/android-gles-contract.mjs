// The android-gles leg's AndroidGlesShaders.kt: the GLES 3.00 visuals in catalog order with their
// catalog fields (catalog.mjs), as typed Kotlin plus two length-prefixed payloads and their
// domain-separated SHA-256 digests, so a consumer can check what it embeds. Contract 1.0.0: the
// package, object, domains, payload layout and text probes are fixed; a change to any is a new
// contract version. Ported from beamfall-visual-shaders tools/android-gles-contract.mjs, which
// produced the contract up to Oscillux v0.2.0; only the GENERATED line changes.
import { createHash } from 'node:crypto';
import { catalogVisuals } from './catalog.mjs';
import { kotlinString } from './kotlin-string.mjs';

export const ANDROID_GLES_CONTRACT_PATH = 'AndroidGlesShaders.kt';
export const ANDROID_GLES_CONTRACT_VERSION = '1.0.0';
export const ANDROID_GLES_PACKAGE = 'com.beamfall.kit.visuals';
export const ANDROID_GLES_OBJECT = 'AndroidGlesShaders';
export const ANDROID_GLES_VISUAL_COUNT = 62;
export const ANDROID_GLES_CATALOG_DOMAIN = 'beamfall.android-gles.catalog.v1';
export const ANDROID_GLES_SOURCE_DOMAIN = 'beamfall.android-gles.source.v1';
export const ANDROID_GLES_TEXT_PROBES = Object.freeze([
  Object.freeze({ name: 'empty', value: '' }),
  Object.freeze({ name: 'plain', value: 'plain text' }),
  Object.freeze({ name: 'quotes', value: 'quotes: "double", \'single\'' }),
  Object.freeze({ name: 'backslashes', value: 'backslashes: \\ \\\\ \\n stays textual' }),
  Object.freeze({ name: 'dollars', value: 'dollars: $ ${value} $$ ${"nested"}' }),
  Object.freeze({ name: 'raw-delimiters', value: 'triple delimiters: """ middle """ and adjacent """"""' }),
  Object.freeze({ name: 'line-feed', value: 'line one\nline two' }),
  Object.freeze({ name: 'carriage-return', value: 'line one\rline two' }),
  Object.freeze({ name: 'crlf', value: 'line one\r\nline two' }),
  Object.freeze({ name: 'unicode', value: 'Beamfall 🪩 café 東京' }),
  Object.freeze({ name: 'combining', value: 'e\u0301' }),
]);

const POST_FX_KEYS = [
  'bloomStrength', 'bloomThreshold', 'trailDecay', 'chroma', 'vignette', 'grain',
];

/** The provenance line for a release: its tag and the 40-hex rev it was cut from. */
export function androidGlesProvenance(tag, rev) {
  if (typeof tag !== 'string' || !/^v\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/.test(tag)) throw new Error('Android GLES provenance tag must be vX.Y.Z');
  if (typeof rev !== 'string' || !/^[0-9a-f]{40}$/.test(rev)) throw new Error('Android GLES provenance rev must be 40 hex digits');
  return `// Shaders: Oscillux ${tag} (beamfall/oscillux@${rev}), AGPL-3.0-only ` +
    '(open source), used under the owner\'s commercial grant (ADR-0228 D4).';
}

/** The contract inputs for a loaded manifest or release set: every visual, in catalogOrder. */
export function androidGlesInputs(manifest, tag, rev) {
  const { wrapGLSL300, VERTEX_300 } = manifest.wrapper;
  return {
    entries: catalogVisuals(manifest).map(entry => {
      const v = manifest.byId.get(entry.id);
      return { ...entry, fragment: (v.wrapper?.wrapGLSL300 ?? wrapGLSL300)(v.body, entry.imageInput) };
    }),
    vertex: VERTEX_300,
    provenance: androidGlesProvenance(tag, rev),
    expectedIds: [...manifest.catalogOrder],
  };
}

export function renderAndroidGlesContract(inputs) {
  const source = renderValidated(inputs);
  verifyAndroidGlesContract(source, inputs);
  return source;
}

function renderValidated({ entries, vertex, expectedIds, provenance }) {
  validateInputs(entries, vertex, expectedIds);
  validProvenance(provenance);
  const catalogPayload = catalogPayloadFor(entries);
  const sourcePayload = sourcePayloadFor(entries, vertex);
  const catalogDigest = digestPayload(ANDROID_GLES_CATALOG_DOMAIN, catalogPayload);
  const sourceDigest = digestPayload(ANDROID_GLES_SOURCE_DOMAIN, sourcePayload);
  const source = `// GENERATED by oscillux tools/shader/bundle-legs.mjs — do not edit.
${provenance}
package ${ANDROID_GLES_PACKAGE}

object ${ANDROID_GLES_OBJECT} {
    const val CONTRACT_VERSION = ${JSON.stringify(ANDROID_GLES_CONTRACT_VERSION)}
    const val CATALOG_DOMAIN = ${JSON.stringify(ANDROID_GLES_CATALOG_DOMAIN)}
    const val SOURCE_DOMAIN = ${JSON.stringify(ANDROID_GLES_SOURCE_DOMAIN)}
    const val CATALOG_SHA256_BASE64 = ${JSON.stringify(catalogDigest)}
    const val SOURCE_SHA256_BASE64 = ${JSON.stringify(sourceDigest)}
    val CATALOG_PAYLOAD_BASE64: String = listOf(
${renderBase64Chunks(catalogPayload)}
    ).joinToString("")
    val SOURCE_PAYLOAD_BASE64: String = listOf(
${renderBase64Chunks(sourcePayload)}
    ).joinToString("")

    data class Param(val key: String, val label: String, val defaultValue: Double)
    data class PostFX(
        val bloomStrength: Double, val bloomThreshold: Double, val trailDecay: Double,
        val chroma: Double, val vignette: Double, val grain: Double,
    )
    data class Palette(val index: Int, val phase: Double)
    data class TextProbe(val name: String, val value: String)
    data class Def(
        val id: String, val name: String, val tier: String, val input: String,
        val overlay: Boolean, val calm: Boolean, val blurb: String,
        val params: List<Param>, val postFX: PostFX, val imageCapable: Boolean,
        val palette: Palette, val fragment: String,
    )

    val VERTEX_300: String = ${kotlinString(vertex)}
    val textProbes: List<TextProbe> = listOf(
${ANDROID_GLES_TEXT_PROBES.map(renderProbe).join('\n')}
    )
    val all: List<Def> = listOf(
${entries.map(renderEntry).join('\n')}
    )
}
`;
  return source;
}

export function verifyAndroidGlesContract(source, inputs) {
  if (typeof source !== 'string') throw new TypeError('Android GLES contract must be text');
  validateInputs(inputs.entries, inputs.vertex, inputs.expectedIds);
  const catalogPayload = readPayload(source, 'CATALOG');
  const sourcePayload = readPayload(source, 'SOURCE');
  assertDigest(source, 'CATALOG', ANDROID_GLES_CATALOG_DOMAIN, catalogPayload);
  assertDigest(source, 'SOURCE', ANDROID_GLES_SOURCE_DOMAIN, sourcePayload);
  if (!catalogPayload.equals(catalogPayloadFor(inputs.entries))) throw new Error('catalog payload does not match typed metadata');
  if (!sourcePayload.equals(sourcePayloadFor(inputs.entries, inputs.vertex))) throw new Error('source payload does not match emitted sources and probes');
  assertSameIds(inputs.expectedIds, emittedIds(source));
  if (source !== renderValidated(inputs)) throw new Error('Android GLES emitted source does not match canonical typed contract');
}

export function digestPayload(domain, payload) {
  return createHash('sha256')
    .update(domain, 'ascii')
    .update(Buffer.from([0]))
    .update(payload)
    .digest('base64');
}

function validateInputs(entries, vertex, expectedIds) {
  if (!Array.isArray(entries) || !Array.isArray(expectedIds)) throw new TypeError('Android GLES entries and expected IDs must be arrays');
  if (expectedIds.length !== ANDROID_GLES_VISUAL_COUNT) {
    throw new Error(`Android GLES expected inventory must contain ${ANDROID_GLES_VISUAL_COUNT} IDs`);
  }
  if (new Set(expectedIds).size !== expectedIds.length) throw new Error('Android GLES expected inventory contains duplicate IDs');
  if (entries.length !== expectedIds.length) throw new Error('Android GLES contract inventory is missing or extra entries');
  validGlsl(vertex, 'VERTEX_300');

  entries.forEach((entry, index) => {
    if (!isObject(entry)) throw new Error(`Android GLES entry ${index} must be an object`);
    requiredText(entry.id, `entry ${index} id`);
    if (entry.id !== expectedIds[index]) throw new Error(`Android GLES contract ID order mismatch at ${index}`);
    for (const key of ['name', 'tier', 'input', 'blurb']) requiredText(entry[key], `${entry.id}.${key}`);
    if (!['lite', 'standard', 'flagship'].includes(entry.tier)) throw new Error(`${entry.id}.tier is unsupported`);
    boolean(entry.overlay, `${entry.id}.overlay`);
    boolean(entry.calm, `${entry.id}.calm`);
    if (entry.imageCapable !== undefined) boolean(entry.imageCapable, `${entry.id}.imageCapable`);
    if (!Array.isArray(entry.params) || entry.params.length !== 3) throw new Error(`${entry.id}.params must contain three entries`);
    entry.params.forEach((param, paramIndex) => {
      if (!isObject(param)) throw new Error(`${entry.id}.params[${paramIndex}] must be an object`);
      if (param.key !== `param${paramIndex}`) throw new Error(`${entry.id}.params[${paramIndex}].key is invalid`);
      requiredText(param.label, `${entry.id}.params[${paramIndex}].label`);
      finite(param.def, `${entry.id}.params[${paramIndex}].def`);
    });
    if (!isObject(entry.postFX)) throw new Error(`${entry.id}.postFX must be an object`);
    for (const key of POST_FX_KEYS) finite(entry.postFX[key], `${entry.id}.postFX.${key}`);
    if (!isObject(entry.palette)) throw new Error(`${entry.id}.palette must be an object`);
    if (!Number.isInteger(entry.palette.index)) throw new Error(`${entry.id}.palette.index must be an integer`);
    finite(entry.palette.phase, `${entry.id}.palette.phase`);
    validGlsl(entry.fragment, `${entry.id}.fragment`);
  });
  ANDROID_GLES_TEXT_PROBES.forEach((probe, index) => {
    requiredText(probe.name, `probe ${index} name`);
    supportedText(probe.value, `probe ${probe.name} value`, true);
  });
}

function renderEntry(entry) {
  const fx = entry.postFX;
  return `        Def(
            id = ${kotlinString(entry.id)}, name = ${kotlinString(entry.name)}, tier = ${kotlinString(entry.tier)},
            input = ${kotlinString(entry.input)}, overlay = ${entry.overlay}, calm = ${entry.calm},
            blurb = ${kotlinString(entry.blurb)},
            params = listOf(${entry.params.map(param => `Param(${kotlinString(param.key)}, ${kotlinString(param.label)}, ${kotlinDouble(param.def)})`).join(', ')}),
            postFX = PostFX(${POST_FX_KEYS.map(key => kotlinDouble(fx[key])).join(', ')}),
            imageCapable = ${!!entry.imageCapable}, palette = Palette(${entry.palette.index}, ${kotlinDouble(entry.palette.phase)}),
            fragment = ${kotlinString(entry.fragment)},
        ),`;
}

function renderProbe(probe) {
  const value = probe.value.includes('\r') ? kotlinUtf8Bytes(probe.value) : kotlinString(probe.value);
  return `        TextProbe(${kotlinString(probe.name)}, ${value}),`;
}

function kotlinUtf8Bytes(value) {
  const bytes = [...Buffer.from(value, 'utf8')].map(byteValue => byteValue > 127 ? byteValue - 256 : byteValue);
  return `String(byteArrayOf(${bytes.join(', ')}), Charsets.UTF_8)`;
}

function renderBase64Chunks(payload) {
  const chunks = payload.toString('base64').match(/.{1,32768}/g) ?? [''];
  return chunks.map(chunk => `        ${JSON.stringify(chunk)},`).join('\n');
}

function catalogPayloadFor(entries) {
  const fields = [utf8(ANDROID_GLES_CONTRACT_VERSION), uint32(entries.length)];
  for (const entry of entries) {
    fields.push(utf8(entry.id), utf8(entry.name), utf8(entry.tier), utf8(entry.input));
    fields.push(byte(entry.overlay), byte(entry.calm), utf8(entry.blurb), uint32(entry.params.length));
    for (const param of entry.params) fields.push(utf8(param.key), utf8(param.label), float64(param.def));
    for (const key of POST_FX_KEYS) fields.push(float64(entry.postFX[key]));
    fields.push(byte(!!entry.imageCapable), int32(entry.palette.index), float64(entry.palette.phase));
  }
  return lengthPrefixed(fields);
}

function sourcePayloadFor(entries, vertex) {
  const fields = [utf8(vertex), uint32(entries.length)];
  for (const entry of entries) fields.push(utf8(entry.id), utf8(entry.fragment));
  fields.push(uint32(ANDROID_GLES_TEXT_PROBES.length));
  for (const probe of ANDROID_GLES_TEXT_PROBES) fields.push(utf8(probe.name), utf8(probe.value));
  return lengthPrefixed(fields);
}

function lengthPrefixed(fields) {
  return Buffer.concat(fields.flatMap(field => [uint32(field.length), field]));
}

function readPayload(source, label) {
  const block = capture(
    source,
    new RegExp(`val ${label}_PAYLOAD_BASE64: String = listOf\\(\\n([\\s\\S]*?)\\n    \\)\\.joinToString\\(""\\)`),
    `${label} payload`,
  );
  const chunks = [...block.matchAll(/^        ("[A-Za-z0-9+/=]*"),$/gm)].map(match => JSON.parse(match[1]));
  if (!chunks.length) throw new Error(`missing or malformed ${label.toLowerCase()} payload`);
  return decodeBase64(chunks.join(''), `${label.toLowerCase()} payload`);
}

function assertDigest(source, label, domain, payload) {
  const digest = capture(source, new RegExp(`const val ${label}_SHA256_BASE64 = "([A-Za-z0-9+/=]+)"`), `${label} digest`);
  if (!/^[A-Za-z0-9+/]{43}=$/.test(digest)) throw new Error(`malformed ${label.toLowerCase()} SHA-256 digest`);
  if (digestPayload(domain, payload) !== digest) throw new Error(`${label.toLowerCase()} SHA-256 mismatch`);
}

function emittedIds(source) {
  return [...source.matchAll(/^            id = """([a-z0-9]+(?:-[a-z0-9]+)*)""", name =/gm)]
    .map(match => match[1]);
}

function assertSameIds(expected, actual) {
  if (actual.length !== expected.length || actual.some((id, index) => id !== expected[index])) {
    throw new Error('Android GLES emitted ID inventory/order mismatch');
  }
}

function utf8(value) { return Buffer.from(value, 'utf8'); }
function byte(value) { return Buffer.from([value ? 1 : 0]); }
function uint32(value) { const out = Buffer.allocUnsafe(4); out.writeUInt32BE(value); return out; }
function int32(value) { const out = Buffer.allocUnsafe(4); out.writeInt32BE(value); return out; }
function float64(value) { const out = Buffer.allocUnsafe(8); out.writeDoubleBE(value); return out; }

function kotlinDouble(value) {
  if (Object.is(value, -0)) return '-0.0';
  const rendered = String(value);
  return Number.isInteger(value) ? `${rendered}.0` : rendered;
}

// The Oscillux provenance comment (androidGlesProvenance()): one // line.
function validProvenance(value) {
  if (typeof value !== 'string' || !/^\/\/ Shaders: Oscillux [^\r\n]+$/.test(value)) {
    throw new Error('Android GLES provenance must be one "// Shaders: Oscillux ..." comment line');
  }
}

function validGlsl(value, label) {
  requiredText(value, label);
  if (!value.startsWith('#version 300 es\n')) throw new Error(`${label} must be GLSL ES 300`);
}

function requiredText(value, label) { supportedText(value, label, false); }

function supportedText(value, label, allowEmpty) {
  if (typeof value !== 'string' || (!allowEmpty && value.length === 0)) throw new Error(`${label} must be ${allowEmpty ? '' : 'non-empty '}text`);
  for (let index = 0; index < value.length; index += 1) {
    const code = value.charCodeAt(index);
    if ((code < 0x20 && code !== 0x09 && code !== 0x0a && code !== 0x0d)
        || (code >= 0x7f && code <= 0x9f)) throw new Error(`${label} contains forbidden control text`);
    if (code >= 0xd800 && code <= 0xdbff) {
      if (index + 1 >= value.length) throw new Error(`${label} contains unsupported Kotlin text`);
      const next = value.charCodeAt(index + 1);
      if (next < 0xdc00 || next > 0xdfff) throw new Error(`${label} contains unsupported Kotlin text`);
      index += 1;
    } else if (code >= 0xdc00 && code <= 0xdfff) throw new Error(`${label} contains unsupported Kotlin text`);
  }
}

function boolean(value, label) {
  if (typeof value !== 'boolean') throw new Error(`${label} must be boolean`);
}

function finite(value, label) {
  if (typeof value !== 'number' || !Number.isFinite(value)) throw new Error(`${label} must be finite`);
}

function isObject(value) { return value !== null && typeof value === 'object' && !Array.isArray(value); }

function capture(source, pattern, label) {
  const match = source.match(pattern);
  if (!match) throw new Error(`missing or malformed ${label}`);
  return match[1];
}

function decodeBase64(encoded, label) {
  if (encoded.length % 4 !== 0) throw new Error(`malformed ${label}`);
  const decoded = Buffer.from(encoded, 'base64');
  if (decoded.toString('base64') !== encoded) throw new Error(`malformed ${label}`);
  return decoded;
}
