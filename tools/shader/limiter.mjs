// Wraps the frame flash limiter passes (shaders/limiter/, README.md there) for the reference
// hosts: GLSL ES 3.00 for WebGL2, and GLSL 450 compiled through glslangValidator and SPIRV-Cross
// to Metal, as present.mjs wraps the present pass.
//
// Every pass: LimiterBlock (32 bytes: vec4 limiter0, vec4 limiter1) at buffer 0 (WebGL2:
// uniform block binding 0); its textures at textures 0.. in LIMITER_PASSES order; sampler 0
// (Metal only; every read is a texel fetch); its outputs at colours 0... The rows partial sums
// are RGBA32UI (Metal rgba32Uint), the other uint textures RGBA16UI (rgba16Uint); uFrame, uHist
// and oColor are RGBA8 (rgba8Unorm).
//
//   node tools/shader/limiter.mjs --write   rewrites shaders/limiter/luma-lut.glsl
//   node tools/shader/limiter.mjs --check   the LUT golden, then (with the pinned toolchain on
//                                           PATH) every pass through glslangValidator as GLSL ES
//                                           3.00 and through SPIRV-Cross to Metal, with the ABI
//                                           checked against LIMITER_PASSES.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { assertShaderToolchain, compileGLSLToSPV, PINNED_GLSLANG, PINNED_SPIRV_CROSS_STAMP, run, withTempDir } from './glsl2msl.mjs';
import { LUMA_LUT } from './limiter-model.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const DIR = join(ROOT, 'shaders', 'limiter');
export const LUT_PATH = join(DIR, 'luma-lut.glsl');
export const LIMITER_BLOCK_SIZE = 32;

/** Pass order, framebuffer size ('rows' 64 x frame height, 'blocks' 64 x 36, 'cells' 16 x 9,
 * 'one' 1 x 1, 'frame'), textures and outputs ([name, type]): 'float' RGBA8, 'uint' RGBA16UI,
 * 'uint32' RGBA32UI. */
export const LIMITER_PASSES = Object.freeze([
  { name: 'rows', size: 'rows', lut: true, textures: [['uFrame', 'float']], outputs: [['oR', 'uint32']] },
  { name: 'reduce', size: 'blocks', textures: [['uRows', 'uint32'], ['uT0', 'uint'], ['uT1', 'uint']], outputs: [['oS', 'uint']] },
  { name: 'cells', size: 'cells', textures: [['uS', 'uint'], ['uT2', 'uint']], outputs: [['oC', 'uint']] },
  { name: 'windows', size: 'cells', textures: [['uC', 'uint']], outputs: [['oW', 'uint']] },
  { name: 'grant', size: 'one', textures: [['uC', 'uint'], ['uW', 'uint'], ['uG', 'uint']], outputs: [['oG', 'uint']] },
  { name: 'state', size: 'blocks', textures: [['uS', 'uint'], ['uG', 'uint'], ['uT0', 'uint'], ['uT1', 'uint'], ['uT2', 'uint']],
    outputs: [['oT0', 'uint'], ['oT1', 'uint'], ['oT2', 'uint']] },
  { name: 'output', size: 'frame', textures: [['uFrame', 'float'], ['uHist', 'float'], ['uT1', 'uint']], outputs: [['oColor', 'float']] },
]);
export const limiterFunction = pass => `oscillux_limiter_${pass.name}`;

export function lumaLutGLSL() {
  const rows = [];
  for (let k = 0; k < 256; k += 4) {
    rows.push('    ' + LUMA_LUT.slice(k, k + 4).map(v => `ivec4(${v.join(', ')})`).join(', '));
  }
  return `// SPDX-License-Identifier: AGPL-3.0-only
// GENERATED by tools/shader/limiter.mjs --write from LUMA_LUT (tools/shader/limiter-model.mjs):
// per 8-bit display value k, round(65535 * w * linear(k / 255)) for the Rec. 709 weights
// w = 0.2126, 0.7152, 0.0722 (x, y, z: R, G, B) and the linear code round(65535 * linear(k / 255))
// (w). Do not hand-edit.
const ivec4 LUMA_LUT[256] = ivec4[256](
${rows.join(',\n')}
);
`;
}

function body(pass) {
  const src = f => readFileSync(join(DIR, f), 'utf8');
  return (pass.lut ? src('luma-lut.glsl') : '') + src('common.glsl') + src(`${pass.name}.glsl`);
}

const BLOCK = `{
    vec4 limiter0;
    vec4 limiter1;
} lu;`;

export function limiterGLSL300(pass) {
  const tex = pass.textures.map(([n, t]) => `uniform highp ${t === 'float' ? 'sampler2D' : 'usampler2D'} ${n};`).join('\n');
  const out = pass.outputs.map(([n, t], i) => `layout(location = ${i}) out ${t === 'float' ? 'vec4' : 'uvec4'} ${n};`).join('\n');
  return `#version 300 es
precision highp float;
precision highp int;
layout(std140) uniform LimiterBlock ${BLOCK}
${tex}
${out}
#define LIM_F(t, px) texelFetch(t, px, 0)
#define LIM_U(t, px) texelFetch(t, px, 0)
#define LIM_SIZE(t) textureSize(t, 0)
#define LIM_USIZE(t) textureSize(t, 0)
${body(pass)}`;
}

export function limiterGLSL450(pass) {
  const tex = pass.textures.map(([n, t], i) => `layout(set = 0, binding = ${i}) uniform ${t === 'float' ? 'texture2D' : 'utexture2D'} ${n};`).join('\n');
  const out = pass.outputs.map(([n, t], i) => `layout(location = ${i}) out ${t === 'float' ? 'vec4' : 'uvec4'} ${n};`).join('\n');
  return `#version 450
layout(set = 0, binding = 0, std140) uniform LimiterBlock ${BLOCK}
${tex}
layout(set = 0, binding = 0) uniform sampler uSamp;
${out}
#define LIM_F(t, px) texelFetch(sampler2D(t, uSamp), px, 0)
#define LIM_U(t, px) texelFetch(usampler2D(t, uSamp), px, 0)
#define LIM_SIZE(t) textureSize(sampler2D(t, uSamp), 0)
#define LIM_USIZE(t) textureSize(usampler2D(t, uSamp), 0)
${body(pass)}`;
}

/** Metal source for one pass, entry point limiterFunction(pass); checks the reflected ABI. */
export function limiterMSL(pass) {
  return withTempDir(`limiter-${pass.name}`, dir => {
    const spv = compileGLSLToSPV(limiterGLSL450(pass), dir);
    const reflection = JSON.parse(run('spirv-cross', [spv, '--reflect']));
    const msl = run('spirv-cross', [
      spv, '--msl', '--msl-decoration-binding', '--msl-force-native-arrays',
      '--rename-entry-point', 'main', limiterFunction(pass), 'frag',
    ]);
    checkABI(pass, msl, reflection);
    return `// SPDX-License-Identifier: AGPL-3.0-only
// GENERATED from shaders/limiter/${pass.name}.glsl by glslangValidator ${PINNED_GLSLANG} + SPIRV-Cross ${PINNED_SPIRV_CROSS_STAMP}.

${msl}`;
  });
}

function checkABI(pass, msl, reflection) {
  const where = `limiter ${pass.name}`;
  // SPIRV-Cross drops resources a pass never reads; whatever remains must sit at its binding.
  pass.textures.forEach(([name], i) => {
    const found = (reflection.separate_images || []).find(r => r.name === name);
    if (!found || found.binding !== i) throw new Error(`${where}: SPIR-V binding of ${name} is not ${i}`);
  });
  const ubo = (reflection.ubos || []).find(r => r.name === 'LimiterBlock');
  if (ubo && (ubo.binding !== 0 || ubo.block_size > LIMITER_BLOCK_SIZE)) throw new Error(`${where}: LimiterBlock binding/size`);
  const checks = [
    new RegExp(`fragment\\s+\\w+\\s+${limiterFunction(pass)}\\(`),
    ...pass.textures.map((_, i) => new RegExp(`\\[\\[texture\\(${i}\\)\\]\\]`)),
    ...pass.outputs.map(([, t], i) => new RegExp(`${t === 'float' ? 'float4' : 'uint4'} \\w+ \\[\\[color\\(${i}\\)\\]\\]`)),
  ];
  for (const re of checks) if (!re.test(msl)) throw new Error(`${where}: MSL has no ${re.source}`);
}

function validateGLSL300(pass) {
  withTempDir(`limiter-es-${pass.name}`, dir => {
    const frag = join(dir, 'limiter.frag');
    writeFileSync(frag, limiterGLSL300(pass));
    run('glslangValidator', ['-S', 'frag', frag]);
  });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--write')) {
    writeFileSync(LUT_PATH, lumaLutGLSL());
    console.log(`wrote ${LUT_PATH}`);
  } else if (process.argv.includes('--check')) {
    if (readFileSync(LUT_PATH, 'utf8') !== lumaLutGLSL()) {
      console.error('shaders/limiter/luma-lut.glsl differs from LUMA_LUT; run node tools/shader/limiter.mjs --write');
      process.exit(1);
    }
    assertShaderToolchain();
    for (const pass of LIMITER_PASSES) {
      validateGLSL300(pass);
      const msl = limiterMSL(pass);
      console.log(`ok   limiter ${pass.name}: GLSL ES 3.00, Metal ${msl.split('\n').length} lines`);
    }
  } else {
    console.error('usage: limiter.mjs --write | --check');
    process.exit(2);
  }
}
