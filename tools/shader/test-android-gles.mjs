import { catalogDocument, catalogVisuals } from './catalog.mjs';
import { kotlinString } from './kotlin-string.mjs';
import { loadManifest } from './manifest.mjs';
import {
  ANDROID_GLES_CATALOG_DOMAIN,
  ANDROID_GLES_CONTRACT_PATH,
  ANDROID_GLES_CONTRACT_VERSION,
  ANDROID_GLES_OBJECT,
  ANDROID_GLES_PACKAGE,
  ANDROID_GLES_SOURCE_DOMAIN,
  ANDROID_GLES_TEXT_PROBES,
  ANDROID_GLES_VISUAL_COUNT,
  androidGlesInputs,
  androidGlesProvenance,
  renderAndroidGlesContract,
  verifyAndroidGlesContract,
} from './android-gles-contract.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../..');
const MANIFEST = loadManifest(join(ROOT, 'shaders/manifest.json'));
// The release the last visual-shaders contract was generated from; the payload digests below are
// its values, so a change to any visual's catalog fields, effect data or GLES source fails here
// until they are updated on purpose.
const TAG = 'v0.2.0';
const REV = 'ea319a10f2c4e90cbcf5d64f928a85bd97ae197e';
const PROVENANCE = androidGlesProvenance(TAG, REV);
const DOLLAR_EXPRESSION = '${"$"}';
const RAW_DELIMITER_EXPRESSION = '${"\\"\\"\\""}';
const INPUTS = realInputs();
const RENDERED = renderAndroidGlesContract(INPUTS);
const POST_FX_KEYS = ['bloomStrength', 'bloomThreshold', 'trailDecay', 'chroma', 'vignette', 'grain'];

test('v1 contract is complete, ordered, deterministic, and independently digest-verifiable', () => {
  assert.equal(renderAndroidGlesContract(realInputs()), RENDERED);
  assert.equal(INPUTS.entries.length, 61);
  assert.equal(ANDROID_GLES_VISUAL_COUNT, MANIFEST.visuals.length);
  assert.equal(RENDERED.split('\n')[0], '// GENERATED by oscillux tools/shader/bundle-legs.mjs — do not edit.');
  assert.match(RENDERED, new RegExp(`package ${escapeRegExp(ANDROID_GLES_PACKAGE)}`));
  assert.match(RENDERED, new RegExp(`object ${ANDROID_GLES_OBJECT}`));
  assert.match(RENDERED, new RegExp(`CONTRACT_VERSION = "${ANDROID_GLES_CONTRACT_VERSION}"`));
  assert.match(RENDERED, new RegExp(`CATALOG_DOMAIN = "${escapeRegExp(ANDROID_GLES_CATALOG_DOMAIN)}"`));
  assert.match(RENDERED, new RegExp(`SOURCE_DOMAIN = "${escapeRegExp(ANDROID_GLES_SOURCE_DOMAIN)}"`));
  assert.equal(constant(RENDERED, 'CATALOG_SHA256_BASE64'), '0FJd+fNCkM4b2Oz8SnYYe350CImj6I/yILQ7RBA08Kg=');
  assert.equal(constant(RENDERED, 'SOURCE_SHA256_BASE64'), 't5AVYA50olEeuavDck5qeQVJPr99tNumOjxp38H6yq4=');
  assert.equal(independentDigest(ANDROID_GLES_CATALOG_DOMAIN, payload(RENDERED, 'CATALOG')),
    constant(RENDERED, 'CATALOG_SHA256_BASE64'));
  assert.equal(independentDigest(ANDROID_GLES_SOURCE_DOMAIN, payload(RENDERED, 'SOURCE')),
    constant(RENDERED, 'SOURCE_SHA256_BASE64'));
  assert.deepEqual(emittedIds(RENDERED), INPUTS.expectedIds);
  assert.equal([...RENDERED.matchAll(/^        Def\($/gm)].length, 61);
  assert.equal([...RENDERED.matchAll(/^        TextProbe\(/gm)].length, ANDROID_GLES_TEXT_PROBES.length);
  verifyAndroidGlesContract(RENDERED, INPUTS);
});

test('typed metadata emits every field losslessly and defaults absent imageCapable to false', () => {
  assert.match(RENDERED, /val chroma: Double, val vignette: Double, val grain: Double/);
  for (const entry of INPUTS.entries) {
    for (const value of [entry.name, entry.tier, entry.input, entry.blurb]) {
      assert.ok(RENDERED.includes(value), `${entry.id} lost ${JSON.stringify(value)}`);
    }
    for (const param of entry.params) {
      assert.ok(RENDERED.includes(param.key));
      assert.ok(RENDERED.includes(param.label));
      assert.ok(RENDERED.includes(kotlinNumber(param.def)));
    }
    for (const value of Object.values(entry.postFX)) assert.ok(RENDERED.includes(kotlinNumber(value)));
  }

  const withoutImageFlag = realInputs();
  const index = withoutImageFlag.entries.findIndex(entry => entry.imageCapable === true);
  const id = withoutImageFlag.entries[index].id;
  delete withoutImageFlag.entries[index].imageCapable;
  assert.match(renderAndroidGlesContract(withoutImageFlag), new RegExp(`id = """${id}"""[\\s\\S]*?imageCapable = false`));
});

test('duplicate, missing, extra, and reordered target IDs fail closed', () => {
  const missing = realInputs();
  missing.entries.pop();
  assert.throws(() => renderAndroidGlesContract(missing), /missing or extra/);

  const extra = realInputs();
  extra.entries.push(structuredClone(extra.entries[0]));
  assert.throws(() => renderAndroidGlesContract(extra), /missing or extra/);

  const duplicate = realInputs();
  duplicate.expectedIds[1] = duplicate.expectedIds[0];
  assert.throws(() => renderAndroidGlesContract(duplicate), /duplicate IDs/);

  const reordered = realInputs();
  [reordered.entries[0], reordered.entries[1]] = [reordered.entries[1], reordered.entries[0]];
  assert.throws(() => renderAndroidGlesContract(reordered), /ID order mismatch/);

  assert.throws(
    () => verifyAndroidGlesContract(RENDERED.replace('id = """pulse"""', 'id = """starfield"""'), INPUTS),
    /inventory|canonical typed contract/,
  );
});

test('missing or malformed metadata categories and all six postFX fields fail closed', () => {
  for (const field of ['name', 'tier', 'input', 'blurb', 'overlay', 'calm', 'params', 'postFX', 'palette', 'fragment']) {
    const inputs = realInputs();
    delete inputs.entries[0][field];
    assert.throws(() => renderAndroidGlesContract(inputs), new RegExp(field === 'fragment' ? 'fragment' : field, 'i'), field);
  }
  for (const field of POST_FX_KEYS) {
    const inputs = realInputs();
    delete inputs.entries[0].postFX[field];
    assert.throws(() => renderAndroidGlesContract(inputs), new RegExp(`postFX\\.${field}`), field);
  }
  for (const [path, mutate] of [
    ['parameter key', entry => { entry.params[0].key = 'wrong'; }],
    ['parameter label', entry => { delete entry.params[0].label; }],
    ['parameter default', entry => { entry.params[0].def = Number.NaN; }],
    ['palette index', entry => { entry.palette.index = 1.5; }],
    ['palette phase', entry => { entry.palette.phase = Number.POSITIVE_INFINITY; }],
  ]) {
    const inputs = realInputs();
    mutate(inputs.entries[0]);
    assert.throws(() => renderAndroidGlesContract(inputs), /invalid|text|finite|integer/, path);
  }
});

test('invalid GLSL versions and unsupported text fail closed', () => {
  const invalidVertex = realInputs();
  invalidVertex.vertex = invalidVertex.vertex.replace('#version 300 es', '#version 310 es');
  assert.throws(() => renderAndroidGlesContract(invalidVertex), /VERTEX_300 must be GLSL ES 300/);

  const invalidFragment = realInputs();
  invalidFragment.entries[0].fragment = invalidFragment.entries[0].fragment.replace('#version 300 es', '#version 450');
  assert.throws(() => renderAndroidGlesContract(invalidFragment), /fragment must be GLSL ES 300/);

  for (const value of ['bad\0text', 'bad\x01text', 'bad\x80text', '\ud800', '\udc00']) {
    const inputs = realInputs();
    inputs.entries[0].name = value;
    assert.throws(() => renderAndroidGlesContract(inputs), /control|unsupported Kotlin text/);
  }
});

test('all emitted adversarial probes are provenance-bound and CR variants avoid source normalization', () => {
  for (const probe of ANDROID_GLES_TEXT_PROBES) assert.ok(RENDERED.includes(probe.name), probe.name);
  assert.match(RENDERED, /dollars: \$\{"\$"\}/);
  assert.match(RENDERED, /\$\{"\\"\\"\\""\}/);
  assert.match(RENDERED, /TextProbe\("""carriage-return""", String\(byteArrayOf\([^)]*13/);
  assert.match(RENDERED, /TextProbe\("""crlf""", String\(byteArrayOf\([^)]*13, 10/);

  const sourceProbeMutation = RENDERED.replace('TextProbe("""plain""", """plain text""")',
    'TextProbe("""plain""", """changed""")');
  assert.throws(() => verifyAndroidGlesContract(sourceProbeMutation, INPUTS), /canonical typed contract/);
});

test('malformed, non-canonical, stale, and cross-boundary provenance fail closed', () => {
  assert.throws(
    () => verifyAndroidGlesContract(RENDERED.replace(/CATALOG_SHA256_BASE64 = "[^"]+"/, 'CATALOG_SHA256_BASE64 = "bad"'), INPUTS),
    /digest/,
  );
  assert.throws(
    () => verifyAndroidGlesContract(RENDERED.replace(constant(RENDERED, 'CATALOG_SHA256_BASE64'), 'A'.repeat(43) + '='), INPUTS),
    /SHA-256 mismatch/,
  );
  assert.throws(
    () => verifyAndroidGlesContract(RENDERED.replace(/(CATALOG_PAYLOAD_BASE64: String = listOf\(\n        ")A/, '$1B'), INPUTS),
    /SHA-256 mismatch|malformed/,
  );
  assert.throws(
    () => verifyAndroidGlesContract(RENDERED.replace(ANDROID_GLES_CATALOG_DOMAIN, ANDROID_GLES_SOURCE_DOMAIN), INPUTS),
    /canonical typed contract/,
  );
  assert.throws(
    () => verifyAndroidGlesContract(RENDERED.replace('name = """Pulse"""', 'name = """Stale"""'), INPUTS),
    /canonical typed contract/,
  );
});

test('the contract names its Oscillux provenance and rejects a missing or multi-line one', () => {
  assert.equal(RENDERED.split('\n')[1], PROVENANCE);
  assert.equal(PROVENANCE, `// Shaders: Oscillux ${TAG} (beamfall/oscillux@${REV}), AGPL-3.0-only (open source), ` +
    'used under the owner\'s commercial grant (ADR-0228 D4).');
  assert.throws(() => androidGlesProvenance('0.2.0', REV), /tag/);
  assert.throws(() => androidGlesProvenance(TAG, REV.slice(1)), /rev/);
  assert.throws(() => renderAndroidGlesContract({ ...INPUTS, provenance: undefined }), /provenance/);
  assert.throws(() => renderAndroidGlesContract({ ...INPUTS, provenance: `${PROVENANCE}\npackage x` }), /provenance/);
});

test('Kotlin raw-string construction round-trips adversarial text without claiming runtime execution', () => {
  const fixtures = [
    '',
    'plain text',
    'quotes: "double", \'single\'',
    'backslashes: \\ \\\\ \\n stays textual',
    'dollars: $ ${value} $$ ${"nested"}',
    'triple delimiters: """ middle """ and adjacent """"""',
    'line endings:\r\nnext\nlast\rcarriage',
    'Unicode: Beamfall 🪩 café 東京 e\u0301',
  ];
  for (const fixture of fixtures) assert.equal(decodeKotlinConstruction(kotlinString(fixture)), fixture);
  assert.equal(kotlinString('shader $value'), '"""shader ${"$"}value"""');
  assert.throws(() => kotlinString(null), /must be a string/);
});

test('the catalog lists every visual in catalogOrder with the fields hosts read', () => {
  const doc = catalogDocument(MANIFEST, TAG, REV);
  assert.deepEqual(Object.keys(doc), ['schemaVersion', 'release', 'rev', 'license', 'visuals']);
  assert.deepEqual([doc.schemaVersion, doc.release, doc.rev, doc.license], [1, TAG, REV, 'AGPL-3.0-only']);
  assert.deepEqual(doc.visuals.map(v => v.id), MANIFEST.catalogOrder);
  for (const v of doc.visuals) {
    const source = MANIFEST.byId.get(v.id);
    assert.deepEqual(Object.keys(v), ['id', 'name', 'tier', 'input', 'overlay', 'calm', 'blurb', 'params', 'postFX',
      'imageCapable', 'imageInput', 'palette', 'controls'], v.id);
    assert.deepEqual(v.params.map(p => p.def), source.params, v.id);
    for (const c of source.controls) assert.equal(v.params[Number(c.uniform.slice(-1))].label, c.label, v.id);
    assert.deepEqual(Object.keys(v.postFX), POST_FX_KEYS, v.id);
    assert.equal(v.postFX.trailDecay, source.trailDecay, v.id);
    assert.deepEqual(v.palette, { index: source.palette[0], phase: source.palette[2] }, v.id);
    assert.equal(v.imageInput, source.imageInput, v.id);
  }
  const bare = { ...MANIFEST, byId: new Map(MANIFEST.byId) };
  bare.byId.set('pulse', { ...MANIFEST.byId.get('pulse'), catalog: null });
  assert.throws(() => catalogVisuals(bare), /visual pulse has no catalog fields/);
});

test('bundle-legs writes the android-gles leg: the contract and its sha256 index', () => {
  const out = mkdtempSync(join(tmpdir(), 'oscillux-android-gles-'));
  try {
    execFileSync(process.execPath, [join(ROOT, 'tools/shader/bundle-legs.mjs'), 'android-gles', ROOT, join(out, 'leg'), TAG, REV],
      { stdio: 'pipe' });
    const kt = readFileSync(join(out, 'leg', ANDROID_GLES_CONTRACT_PATH), 'utf8');
    assert.equal(kt, RENDERED);
    const index = JSON.parse(readFileSync(join(out, 'leg', 'index.json'), 'utf8'));
    assert.deepEqual([index.leg, index.release, index.rev, index.license], ['android-gles', TAG, REV, 'AGPL-3.0-only']);
    assert.deepEqual(index.files, [{ path: 'AndroidGlesShaders.kt', sha256: createHash('sha256').update(kt).digest('hex'),
      bytes: Buffer.byteLength(kt) }]);
  } finally {
    rmSync(out, { recursive: true, force: true });
  }
});

function realInputs() {
  return structuredClone(androidGlesInputs(MANIFEST, TAG, REV));
}

function emittedIds(source) {
  return [...source.matchAll(/^            id = """([a-z0-9]+(?:-[a-z0-9]+)*)""", name =/gm)]
    .map(match => match[1]);
}

function constant(source, name) {
  return source.match(new RegExp(`const val ${name} = "([^"]+)"`))[1];
}

function payload(source, name) {
  const block = source.match(new RegExp(`val ${name}_PAYLOAD_BASE64: String = listOf\\(\\n([\\s\\S]*?)\\n    \\)\\.joinToString\\(""\\)`))[1];
  return Buffer.from([...block.matchAll(/^        "([A-Za-z0-9+/=]*)",$/gm)].map(match => match[1]).join(''), 'base64');
}

function independentDigest(domain, bytes) {
  return createHash('sha256').update(domain, 'ascii').update(Buffer.from([0])).update(bytes).digest('base64');
}

function kotlinNumber(value) { return Number.isInteger(value) ? `${value}.0` : String(value); }

function escapeRegExp(value) { return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); }

function decodeKotlinConstruction(encoded) {
  assert.ok(encoded.startsWith('"""') && encoded.endsWith('"""'));
  const body = encoded.slice(3, -3);
  let decoded = '';
  for (let index = 0; index < body.length;) {
    if (body.startsWith(DOLLAR_EXPRESSION, index)) {
      decoded += '$';
      index += DOLLAR_EXPRESSION.length;
    } else if (body.startsWith(RAW_DELIMITER_EXPRESSION, index)) {
      decoded += '"""';
      index += RAW_DELIMITER_EXPRESSION.length;
    } else {
      assert.notEqual(body.slice(index, index + 3), '"""', 'raw delimiter was not encoded');
      decoded += body[index];
      index += 1;
    }
  }
  return decoded;
}
